def _parse_universal_description(raw: str) -> Optional[Dict[str, str]]:
    """Parse and validate a universal JSON description.

    Handles JSON embedded in prose, markdown code blocks, or plain JSON.
    Falls back to extracting values from prose if no JSON found.
    Returns dict with keys 'gender', 'age', 'pitch', 'accent', 'style', 'celebrity_voice' or None if invalid.
    """
    try:
        text = raw.strip()
        # Try direct parse first
        try:
            obj = json.loads(text)
        except json.JSONDecodeError:
            # Try extracting JSON from markdown code block
            if "```" in text:
                text = text.split("\n", 1)[1] if "\n" in text else text
                if text.endswith("```"):
                    text = text[:-3]
            # Try finding JSON object anywhere in the text
            start = text.find("{")
            end = text.rfind("}") + 1
            if start >= 0 and end > start:
                text = text[start:end]
            try:
                obj = json.loads(text)
            except json.JSONDecodeError:
                # Fallback: extract values from prose
                return _extract_from_prose(raw)
        gender = obj.get("gender", "").lower()
        age = obj.get("age", "").lower()
        pitch = obj.get("pitch", "moderate").lower()
        accent = obj.get("accent", "").lower()
        style = obj.get("style", "")
        celebrity_voice = obj.get("celebrity_voice", "")
        if gender not in ("male", "female"):
            return None
        if age not in ("child", "teenager", "young adult", "middle-aged", "elderly", "young", "middle-aged", "old"):
            return None
        return {"gender": gender, "age": age, "pitch": pitch, "accent": accent, "style": style, "celebrity_voice": celebrity_voice}
    except (json.JSONDecodeError, AttributeError):
        return None


def _extract_from_prose(text: str) -> Optional[Dict[str, str]]:
    """Extract gender, age, pitch from prose output as fallback."""
    import re
    text_lower = text.lower()

    # Extract gender
    gender = None
    if "male" in text_lower or "man" in text_lower or "boy" in text_lower:
        gender = "male"
    elif "female" in text_lower or "woman" in text_lower or "girl" in text_lower:
        gender = "female"
    if not gender:
        return None

    # Extract age
    age = None
    age_patterns = [
        (r"\byoung\b", "young adult"),
        (r"\bchild\b", "child"),
        (r"\bteen\b", "teenager"),
        (r"\bteenager\b", "teenager"),
        (r"\bmiddle-aged\b", "middle-aged"),
        (r"\bmiddle aged\b", "middle-aged"),
        (r"\bold\b", "elderly"),
        (r"\belderly\b", "elderly"),
        (r"\bsenior\b", "elderly"),
    ]
    for pattern, val in age_patterns:
        if re.search(pattern, text_lower):
            age = val
            break
    if not age:
        age = "middle-aged"  # default

    # Extract pitch
    pitch = None
    pitch_patterns = [
        (r"\bvery low\b", "very low"),
        (r"\blow pitch\b", "low"),
        (r"\blow\b", "low"),
        (r"\bmoderate\b", "moderate"),
        (r"\bmedium\b", "moderate"),
        (r"\bhigh pitch\b", "high"),
        (r"\bhigh\b", "high"),
        (r"\bvery high\b", "very high"),
    ]
    for pattern, val in pitch_patterns:
        if re.search(pattern, text_lower):
            pitch = val
            break
    if not pitch:
        pitch = "moderate"  # default

    # Extract accent
    accent = None
    accent_patterns = [
        (r"\bamerican\b", "american"),
        (r"\bbritish\b", "british"),
        (r"\benglish\b", "british"),
        (r"\baustralian\b", "australian"),
        (r"\bcanadian\b", "canadian"),
        (r"\bindian\b", "indian"),
    ]
    for pattern, val in accent_patterns:
        if re.search(pattern, text_lower):
            accent = val
            break

    # Extract style traits
    style_words = []
    style_candidates = [
        "raspy", "gravelly", "smooth", "breathy", "nasal", "booming",
        "whispery", "hoarse", "metallic", "guttural", "warm", "cold",
        "aristocratic", "streetwise", "scholarly", "rural", "deep",
        "soft", "gentle", "sharp", "rough", "clear", "mellow",
        "authoritative", "nervous", "anxious", "calm", "cheerful",
        "dark", "light", "bright", "dark", "warm", "cold",
    ]
    for word in style_candidates:
        if word in text_lower:
            style_words.append(word)
    style = ", ".join(style_words[:3]) if style_words else ""

    # Build description from the prose itself (use first 4 sentences)
    sentences = re.split(r'[.!?]+', text.replace('\n', ' '))
    sentences = [s.strip() for s in sentences if len(s.strip()) > 20]
    description = ". ".join(sentences[:4]) if sentences else text[:200]

    return {
        "gender": gender,
        "age": age,
        "pitch": pitch,
        "accent": accent or "",
        "style": style,
        "description": description,
        "celebrity_voice": "",
    }


def _universal_description_to_omni(parsed: Dict[str, str]) -> str:
    """Convert universal JSON description to OmniVoice comma-separated format."""
    parts = [parsed["gender"], parsed["age"]]
    pitch_map = {"very low": "very low pitch", "low": "low pitch", "moderate": "moderate pitch", "high": "high pitch", "very high": "very high pitch"}
    pitch = pitch_map.get(parsed.get("pitch", "moderate"), "moderate pitch")
    parts.append(pitch)
    if parsed.get("accent"):
        accent_map = {"american": "american accent", "british": "british accent", "australian": "australian accent", "canadian": "canadian accent", "indian": "indian accent", "chinese": "chinese accent", "korean": "korean accent", "japanese": "japanese accent", "portuguese": "portuguese accent", "russian": "russian accent"}
        accent = accent_map.get(parsed["accent"], parsed["accent"])
        parts.append(accent)
    return ", ".join(parts)


def _universal_description_to_dramabox(parsed: Dict[str, str]) -> str:
    """Convert universal JSON description to Dramabox prompt format."""
    parts = [parsed["gender"], parsed["age"]]
    if parsed.get("pitch"):
        parts.append(parsed["pitch"])
    if parsed.get("accent"):
        parts.append(parsed["accent"])
    if parsed.get("style"):
        parts.extend(s.strip() for s in parsed["style"].split(","))
    return ", ".join(parts)


def _universal_description_to_vox(parsed: Dict[str, str]) -> str:
    """Convert universal JSON description to VoxCPM format."""
    parts = [parsed["gender"], parsed["age"]]
    if parsed.get("pitch"):
        parts.append(parsed["pitch"])
    if parsed.get("style"):
        parts.extend(s.strip() for s in parsed["style"].split(","))
    if parsed.get("accent"):
        parts.append(parsed["accent"])
    return f"({', '.join(parts)})"


def describe_character(client: OpenAI, model: str, character: str, context: str, chapter_messages: Optional[List[str]] = None, voice_engine: Optional[str] = None, max_retries: int = 3, used_celebrities: Optional[List[str]] = None) -> str:
    """Ask the LLM to describe a single character.

    Returns the raw JSON string. Engine adapters convert to their format.

    Args:
        client: OpenAI client instance
        model: Model name to use for inference
        character: Character name to describe
        context: Character description context string
        chapter_messages: Optional list of chapter-based dialogue messages
        voice_engine: TTS engine (unused - all engines use same JSON format)
        max_retries: Max retries for failed LLM calls
        used_celebrities: List of celebrity names already assigned to other characters

    Returns:
        Raw JSON string describing the character.
    """
    system_prompt = _get_description_prompt(voice_engine)

    # Add used celebrities constraint to system prompt
    if used_celebrities:
        system_prompt += f"\n\nIMPORTANT: Do NOT use these celebrities (they are already assigned to other characters): {', '.join(used_celebrities)}\nPick a DIFFERENT celebrity for this character."

    # System prompt first
    messages = [
        {"role": "system", "content": system_prompt},
    ]

    # Add chapter messages as separate user messages if provided
    if chapter_messages:
        for chapter_msg in chapter_messages:
            messages.append({"role": "user", "content": chapter_msg})

    # Final user message with the character to describe and summary context
    messages.append({"role": "user", "content": f"Describe this character: {character} \n\nContext:\n{context}"})

    for attempt in range(max_retries):
        try:
            response = client.chat.completions.create(
                model=model,
                messages=messages,
            )
            raw = response.choices[0].message.content
            # Validate universal JSON format
            parsed = _parse_universal_description(raw)
            if parsed:
                # If we got prose, convert parsed result to JSON for storage
                if "description" in parsed:
                    # Prose fallback — return as JSON
                    return json.dumps(parsed)
                return raw  # Return raw JSON for storage
            # Retry with feedback
            messages.append({"role": "assistant", "content": raw})
            messages.append({"role": "user", "content": "Invalid output. Gender must be 'male' or 'female', age must be 'child', 'teenager', 'young adult', 'middle-aged', or 'elderly'. Return valid JSON."})
        except Exception as e:
            if attempt == max_retries - 1:
                return f"Error describing character: {e}"
    return f"Error: Failed to generate valid description for {character} after {max_retries} attempts"


def describe_all_characters(client: OpenAI, model: str, characters: List[str], context: str, voice_engine: Optional[str] = None) -> Dict[str, str]:
    """Ask the LLM to describe all characters at once."""
    system_prompt = _get_description_prompt(voice_engine)

    # Build the user message
    user_message = f"Describe all these characters in detail. Return a JSON object with character names as keys and descriptions as values.\n\nCharacters:\n{chr(10).join(characters)}\n\nContext:\n{context}"

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_message}
    ]

    try:
        response = client.chat.completions.create(
            model=model,
            messages=messages
        )
        content = response.choices[0].message.content
        # Try to parse JSON from response
        try:
            # Remove markdown code blocks if present
            if content.startswith('```json'):
                content = content[7:]
            if content.startswith('```'):
                content = content[3:]
            if content.endswith('```'):
                content = content[:-3]
            content = content.strip()
            parsed = json.loads(content)

            # Validate that the response contains all expected character names
            # Check for at least one matching character name (case-insensitive)
            missing_chars = []
            for char in characters:
                char_lower = char.lower()
                found = any(k.lower() == char_lower for k in parsed.keys())
                if not found:
                    missing_chars.append(char)

            if missing_chars:
                # If we're missing character names, the LLM likely returned the example names
                # Instead of the actual character names - use fallback
                print(f"Warning: LLM response missing character names: {missing_chars}. Using fallback.")
                return {char: content for char in characters}

            return parsed
        except json.JSONDecodeError:
            # If parsing fails, return raw content
            return {char: content for char in characters}
    except Exception as e:
        print(f"Error describing characters: {e}", file=sys.stderr)
        return {}
