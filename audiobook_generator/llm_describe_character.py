def describe_characters_shared(
    characters: List[str],
    chapter_texts: List[str],
    chapter_files: List[Path],
    output_dir: str,
    client: OpenAI,
    model: str,
    wiki_url_template: str = "",
    verbose: bool = False,
    progress_callback: Optional[callable] = None,
    voice_engine: Optional[str] = None,
    max_concurrent: int = 1
) -> Dict[str, str]:
    """Shared logic for describing characters.

    Args:
        characters: List of character names
        chapter_texts: List of chapter text content
        chapter_files: List of chapter file paths
        output_dir: Directory to save output files
        client: OpenAI client instance
        model: Model name to use for inference
        wiki_url_template: Optional URL template for wiki lookup
        verbose: Print verbose output
        progress_callback: Optional callback for progress updates
        voice_engine: TTS engine for voice generation ('omni', 'vox', etc.)
        max_concurrent: Maximum number of concurrent LLM calls (default 1, set higher to parallelize)

    Returns:
        Dict of character descriptions
    """
    # Step 1: De-dupe characters first
    duplicates = find_duplicate_characters(characters)
    if verbose and duplicates:
        print(f"Found duplicate character names: {duplicates}")

    # Create a map from duplicate names to canonical names
    duplicate_replacement_map = create_duplicate_replacement_map(duplicates)
    if verbose and duplicate_replacement_map:
        print(f"Duplicate replacement map: {duplicate_replacement_map}")

    # Get list of canonical characters (exclude duplicates)
    canonical_characters = [
        char for char in characters
        if char not in duplicate_replacement_map
    ]
    if verbose:
        print(f"Canonical characters to describe: {canonical_characters}")

    # Step 2: Loop over canonical characters (parallel if max_concurrent > 1)
    descriptions = {}
    total_chars = len(canonical_characters)

    # Thread-safe set to track used celebrities across parallel workers
    used_celebrities_lock = threading.Lock()
    used_celebrities: set = set()

    if max_concurrent > 1 and total_chars > 1:
        if verbose:
            print(f"Describing {total_chars} characters with {max_concurrent} concurrent workers...")

        def _describe_one(character: str, idx: int) -> Tuple[str, str, str]:
            if verbose:
                print(f"[{idx}/{total_chars}] Describing character: {character}")

            context_result = build_character_context(
                [character], chapter_texts, chapter_files,
                chapters_dir=Path(output_dir), wiki_url_template=wiki_url_template,
                all_characters=canonical_characters
            )
            context = context_result[0]
            chapter_messages = context_result[1] if len(context_result) > 1 else []

            # Get current list of used celebrities (thread-safe read)
            with used_celebrities_lock:
                current_used = list(used_celebrities)

            description = describe_character(client, model, character, context, chapter_messages, voice_engine=voice_engine, used_celebrities=current_used)

            # Extract celebrity from description and add to used set (thread-safe write)
            try:
                desc_obj = json.loads(description) if isinstance(description, str) else description
                if isinstance(desc_obj, dict):
                    celeb = desc_obj.get("celebrity_voice", "")
                    if celeb:
                        with used_celebrities_lock:
                            used_celebrities.add(celeb)
                            if verbose:
                                print(f"  [CELEB-DEDUP] Assigned '{celeb}' to '{character}' (now {len(used_celebrities)} unique celebrities)")
            except (json.JSONDecodeError, AttributeError):
                pass

            debug_output = {
                "model": model,
                "character": character,
                "system_prompt": _get_description_prompt(voice_engine),
                "context": context,
                "description": description,
            }
            debug_file = os.path.join(
                output_dir, f"llm_character_debug_{character.replace(' ', '_')}.json"
            )
            with open(debug_file, "w", encoding="utf-8") as f:
                json.dump(debug_output, f, indent=2, ensure_ascii=False)
            if verbose:
                print(f"  Saved debug output to: {debug_file}")

            return (character, description, f"  Completed: {character}")

        with ThreadPoolExecutor(max_workers=max_concurrent) as executor:
            futures = {executor.submit(_describe_one, char, i + 1): i + 1 for i, char in enumerate(canonical_characters)}
            completed = 0
            for future in as_completed(futures):
                completed += 1
                character, desc, msg = future.result()
                descriptions[character] = desc
                if verbose:
                    print(msg)
                if progress_callback:
                    progress_callback(completed / total_chars, f"Describing: {character}")
    else:
        for idx, character in enumerate(canonical_characters, 1):
            if verbose:
                print(f"[{idx}/{total_chars}] Describing character: {character}")

            context_result = build_character_context(
                [character], chapter_texts, chapter_files,
                chapters_dir=Path(output_dir), wiki_url_template=wiki_url_template,
                all_characters=canonical_characters
            )
            context = context_result[0]
            chapter_messages = context_result[1] if len(context_result) > 1 else []

            description = describe_character(client, model, character, context, chapter_messages, voice_engine=voice_engine, used_celebrities=list(used_celebrities))
            descriptions[character] = description

            # Extract celebrity and add to used set
            try:
                desc_obj = json.loads(description) if isinstance(description, str) else description
                if isinstance(desc_obj, dict):
                    celeb = desc_obj.get("celebrity_voice", "")
                    if celeb:
                        used_celebrities.add(celeb)
                        if verbose:
                            print(f"  [CELEB-DEDUP] Assigned '{celeb}' to '{character}' (now {len(used_celebrities)} unique celebrities)")
            except (json.JSONDecodeError, AttributeError):
                pass

            debug_output = {
                "model": model,
                "character": character,
                "system_prompt": _get_description_prompt(voice_engine),
                "context": context,
                "description": description,
            }
            debug_file = os.path.join(
                output_dir, f"llm_character_debug_{character.replace(' ', '_')}.json"
            )
            with open(debug_file, "w", encoding="utf-8") as f:
                json.dump(debug_output, f, indent=2, ensure_ascii=False)
            if verbose:
                print(f"  Saved debug output to: {debug_file}")

            progress = idx / total_chars if total_chars > 0 else 1.0
            if progress_callback:
                progress_callback(progress, f"Describing: {character}")
            if verbose:
                print(f"  Completed: {character}")

    deduped_descriptions = descriptions

    # Save duplicate replacement map to file
    replacement_map_file = os.path.join(output_dir, "duplicate_replacement_map.json")
    with open(replacement_map_file, 'w', encoding='utf-8') as f:
        json.dump(duplicate_replacement_map, f, indent=2, ensure_ascii=False)
    if verbose:
        print(f"Duplicate replacement map saved to: {replacement_map_file}")

    # Update characters.json with deduplicated list (canonical characters only)
    characters_file_path = os.path.join(output_dir, "characters.json")
    if os.path.exists(characters_file_path):
        with open(characters_file_path, 'r', encoding='utf-8') as f:
            original_data = json.load(f)
        # Update the characters list to only contain canonical names
        original_data['characters'] = canonical_characters
        with open(characters_file_path, 'w', encoding='utf-8') as f:
            json.dump(original_data, f, indent=2, ensure_ascii=False)
        if verbose:
            print(f"Updated characters.json with {len(canonical_characters)} canonical characters")

    # Save results (replacing em dashes with regular hyphens)
    output_file = os.path.join(output_dir, "characters_descriptions.json")
    with open(output_file, 'w', encoding='utf-8') as f:
        # Convert descriptions to JSON string and replace em dash with hyphen
        json_content = json.dumps(deduped_descriptions, indent=2, ensure_ascii=False)
        json_content = json_content.replace('\u2014', '-')
        f.write(json_content)
    if verbose:
        print(f"Character descriptions saved to: {output_file}")

    return deduped_descriptions


